impl GameState {
    pub(crate) fn show_startup_screen(&mut self) {
        let center = self.screen_center();
        clear_screen();
        self.show_logo();
        thread::sleep(Duration::from_millis(LOGO_REVEAL_DELAY_MS));

        clear_screen();
        println!("\n\n");
        for &(line, color_on) in STARTUP_TITLE_LINES {
            typewrite_centered(line, center, color_on, TITLE_DELAY_MS);
            println!();
        }

        println!("\n\n\n\n");
        thread::sleep(Duration::from_millis(TITLE_CARD_DELAY_MS));
        for &(line, color_on) in STARTUP_CREDITS {
            typewrite_centered(line, center, color_on, TITLE_DELAY_MS);
            println!();
        }
        println!("\n\n\n\n");

        print!(
            "{}{} ",
            " ".repeat(center.saturating_sub(13)),
            paint(YELLOW, "DO YOU WANT INSTRUCTIONS?")
        );
        let _ = io::stdout().flush();
        drain_stdin();
    }

    pub(crate) fn show_instructions(&mut self) {
        self.term_info();
        clear_screen();
        println!("\n\n");

        let pad = self.screen_center().saturating_sub(20);
        typewrite_line("DRUG WARS", pad, BOLD_GREEN, RESET, INSTRUCTION_DELAY_MS);
        for line in INSTRUCTION_LINES {
            typewrite_line(line, pad, "", "", INSTRUCTION_DELAY_MS);
        }
        println!();
        for range in DRUG_PRICE_RANGES {
            let line = format_drug_price_range(range);
            typewrite_line(&line, pad, MAGENTA, RESET, INSTRUCTION_DELAY_MS);
        }
        println!("\n\n");
        typewrite_line(
            "    (HIT ANY KEY TO START GAME)",
            pad,
            YELLOW,
            RESET,
            INSTRUCTION_DELAY_MS,
        );

        drain_stdin();
        self.wait_for_key_press();
    }

    fn show_logo(&mut self) {
        self.term_info();
        let padding = " ".repeat(self.screen_center().saturating_sub(30));
        for line in LOGO_LINES {
            println!("{padding}{line}");
        }

        println!();
        typewrite_centered(TAGLINE, self.screen_center(), MAGENTA, TITLE_DELAY_MS);
    }
}

fn typewrite_centered(text: &str, center: usize, color_on: &str, delay_ms: u64) {
    let color_off = if color_on.is_empty() { "" } else { RESET };
    typewrite_line(
        text,
        center.saturating_sub(text.len() / 2),
        color_on,
        color_off,
        delay_ms,
    );
}

fn format_drug_price_range(range: DrugPriceRange) -> String {
    format!(
        "      {:<12}{}-{}",
        range.drug.as_str(),
        range.min_price,
        range.max_price
    )
}

